(function registerNarrator(DSL) {
  "use strict";

  // Narrated mode: a lesson plays like a short film. A voice reads each line (pre-rendered mp3s
  // from tools/voice.py, or the browser's own speech for lines not rendered yet), the visuals
  // animate along, and the film stops whenever the learner has to act or pick a response.
  //
  // chapter = { id, title, continues?, script(n, scene) → Promise }
  // n       = { say, react, show, mount, ask, choose, wait, after, alive, lab, state }
  //
  // Lines are written in narration/<lesson>.json as { id: caption } or { id: { caption, voice, speaker } }.
  // A line with a speaker (like the interviewer) is voiced by that speaker and labelled in the caption.
  // Captions may hold markup and {placeholders}; the voice text never does.

  const { reducedMotion, retrigger } = DSL.LabKit;
  const PREFS_KEY = "dsl-narrator";
  const SPEEDS = [1, 1.25, 1.5];
  const LINE_GAP = 280;
  const IDLE_HINT = 9000;
  const SILENT_WAV = "data:audio/wav;base64,UklGRiQAAABXQVZFZm10IBAAAAABAAEAQB8AAEAfAAABAAgAZGF0YQAAAAA=";
  let active = null;

  function readJson(key, fallback) {
    try {
      return { ...fallback, ...JSON.parse(localStorage.getItem(key) || "{}") };
    } catch (error) {
      return { ...fallback };
    }
  }

  function writeJson(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch (error) {
      // Preferences and resume are conveniences.
    }
  }

  // Captions and audio durations, registered by narration/<lesson>.js (generated by tools/voice.py).
  const narrations = Object.create(null);

  function register(lessonId, bundle) {
    narrations[lessonId] = bundle;
  }

  const stripTags = (html) => html.replace(/<[^>]+>/g, "").replace(/&nbsp;/g, " ");
  const slug = (text) => stripTags(text).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

  // Keywords from every registered lesson, or from one: { id: { term, def, lesson } }.
  // Captions mark them as <k>term</k>, or <k id="term-id">inflected form</k>.
  function keywords(lessonId) {
    const out = {};
    Object.entries(narrations).forEach(([lesson, bundle]) => {
      if (lessonId && lesson !== lessonId) return;
      Object.entries(bundle.keywords || {}).forEach(([id, word]) => { out[id] = { ...word, lesson }; });
    });
    return out;
  }
  const never = () => new Promise(() => {});

  // One pause switch for the whole film: timers, audio and running animations all obey it.
  function createClock() {
    let paused = false;
    let frozen = [];
    const listeners = new Set();
    return {
      get paused() { return paused; },
      set(value) {
        if (value === paused) return;
        paused = value;
        if (paused) {
          frozen = document.getAnimations().filter((animation) => animation.playState === "running");
          frozen.forEach((animation) => animation.pause());
        } else {
          frozen.forEach((animation) => animation.play());
          frozen = [];
        }
        [...listeners].forEach((listener) => listener(paused));
      },
      listen(listener) {
        listeners.add(listener);
        return () => listeners.delete(listener);
      },
      // Resolves after `ms` of unpaused time.
      sleep(ms) {
        return new Promise((resolve) => {
          let left = ms;
          let started = 0;
          let timer = null;
          const run = () => { started = performance.now(); timer = window.setTimeout(finish, left); };
          const stop = this.listen((isPaused) => {
            if (isPaused) {
              window.clearTimeout(timer);
              left -= performance.now() - started;
            } else run();
          });
          function finish() { stop(); resolve(); }
          if (!paused) run();
        });
      },
      ready() {
        if (!paused) return Promise.resolve();
        return new Promise((resolve) => {
          const stop = this.listen((isPaused) => { if (!isPaused) { stop(); resolve(); } });
        });
      },
    };
  }

  // Where the mp3s live: the audio host named in index.html, or the local audio/ folder when the
  // site runs from this machine (tools/voice.py build writes there).
  function audioBase() {
    const local = location.protocol === "file:" || /^(localhost|127\.0\.0\.1|\[::1\])$/.test(location.hostname);
    const meta = document.querySelector('meta[name="audio-base"]');
    return local || !meta || !meta.content ? "audio" : meta.content.replace(/\/+$/, "");
  }

  // Speaks one line at a time. play(id) resolves when the line is over (or skipped).
  function createVoice({ lessonId, lines, manifest, prefs, clock }) {
    const audio = new Audio();
    audio.preload = "auto";
    let finishCurrent = null;
    let englishVoice = null;

    // Lines stream on demand. While one plays, the next two (in script order) are fetched into
    // memory, so they start without a gap even on a slow connection.
    const base = audioBase();
    const order = Object.keys(lines).filter((id) => manifest[id]);
    const fetched = new Map();
    const ready = new Map();
    const PREFETCH = 2;
    const KEEP = 6;
    let current = null;
    const urlFor = (id) => `${base}/${lessonId}/${encodeURIComponent(id)}.mp3?v=${manifest[id].hash}`;

    function release(id) {
      if (id === current) return;
      const url = ready.get(id);
      if (url) URL.revokeObjectURL(url);
      ready.delete(id);
      fetched.delete(id);
    }

    function prefetch(id) {
      if (!manifest[id] || fetched.has(id) || location.protocol === "file:") return;
      fetched.set(id, true);
      fetch(urlFor(id), { priority: "low" })
        .then((response) => (response.ok ? response.blob() : null))
        .then((blob) => { if (blob && fetched.has(id)) ready.set(id, URL.createObjectURL(blob)); })
        .catch(() => fetched.delete(id));
      if (fetched.size > KEEP) {
        const oldest = [...fetched.keys()].find((key) => key !== current && key !== id);
        if (oldest) release(oldest);
      }
    }

    function prefetchAfter(id) {
      const at = order.indexOf(id);
      order.slice(at + 1, at + 1 + PREFETCH).forEach(prefetch);
    }

    function spoken(id) {
      const line = lines[id];
      if (!line) return id;
      return typeof line === "string" ? stripTags(line) : line.voice || stripTags(line.caption);
    }

    function readingTime(id) {
      const entry = manifest[id];
      if (entry) return entry.ms / prefs.speed;
      return Math.max(1400, spoken(id).split(/\s+/).length * 330) / prefs.speed;
    }

    // Voices load late (and some browsers, like Brave, may report none), so keep asking until one shows up.
    function pickVoice() {
      if (englishVoice) return englishVoice;
      const voices = window.speechSynthesis ? speechSynthesis.getVoices().filter((voice) => /^en[-_]/i.test(voice.lang)) : [];
      englishVoice = voices.find((voice) => /natural|premium|enhanced|google/i.test(voice.name)) || voices[0] || null;
      return englishVoice;
    }

    function stop() {
      if (finishCurrent) finishCurrent();
    }

    function play(id) {
      stop();
      return new Promise((resolve) => {
        const cleanups = [];
        let settled = false;
        const finish = () => {
          if (settled) return;
          settled = true;
          finishCurrent = null;
          cleanups.forEach((cleanup) => cleanup());
          resolve();
        };
        finishCurrent = finish;
        const onPause = (handler) => cleanups.push(clock.listen(handler));

        // Muted, or nothing can speak: hold the caption for its reading time.
        const silent = () => clock.sleep(readingTime(id)).then(finish);

        if (prefs.muted) return silent();

        const entry = manifest[id];
        if (entry) {
          current = id;
          audio.src = ready.get(id) || urlFor(id);
          prefetchAfter(id);
          audio.playbackRate = prefs.speed;
          const ended = () => finish();
          const failed = () => { if (!settled) silent(); };
          audio.addEventListener("ended", ended);
          audio.addEventListener("error", failed);
          cleanups.push(() => {
            audio.removeEventListener("ended", ended);
            audio.removeEventListener("error", failed);
            audio.pause();
          });
          onPause((paused) => (paused ? audio.pause() : audio.play().catch(failed)));
          if (!clock.paused) audio.play().catch(failed);
          return undefined;
        }

        if (window.speechSynthesis && pickVoice()) {
          const speak = () => {
            const utterance = new SpeechSynthesisUtterance(spoken(id));
            utterance.voice = pickVoice();
            utterance.rate = prefs.speed;
            utterance.onend = () => { if (!clock.paused) finish(); };
            utterance.onerror = () => { if (!clock.paused) finish(); };
            speechSynthesis.speak(utterance);
          };
          // Browser speech can't pause reliably, so a paused line restarts from its beginning.
          onPause((paused) => { speechSynthesis.cancel(); if (!paused) speak(); });
          cleanups.push(() => speechSynthesis.cancel());
          if (!clock.paused) speak();
          return undefined;
        }

        return silent();
      });
    }

    function setSpeed() {
      audio.playbackRate = prefs.speed;
    }

    // Must run inside a click: browsers only allow audio after a user gesture.
    function unlock() {
      audio.src = SILENT_WAV;
      audio.play().catch(() => {});
      if (window.speechSynthesis) speechSynthesis.getVoices();
    }

    order.slice(0, PREFETCH).forEach(prefetch);

    return { play, stop, unlock, setSpeed };
  }

  function run({ lessonId, title, chapters, onLab }) {
    const root = DSL.elements.root;
    const { lines = {}, audio: manifest = {}, speakers = {}, keywords: lessonWords = {} } = narrations[lessonId] || {};

    const saveKey = `dsl-narrated-${lessonId}`;
    const saved = readJson(saveKey, { index: 0, done: [] });
    const prefs = readJson(PREFS_KEY, { speed: 1, muted: false });
    const clock = createClock();
    const voice = createVoice({ lessonId, lines, manifest, prefs, clock });
    const done = new Set((saved.done || []).filter((id) => chapters.some((chapter) => chapter.id === id)));
    const state = {};
    let index = Math.min(Math.max(Number(saved.index) || 0, 0), chapters.length - 1);
    let token = 0;
    let started = false;
    let choiceKeys = null;

    root.innerHTML = `<div class="gd nr">
      <header class="gd-bar">
        <button type="button" class="gd-icon" data-nav-toggle aria-label="Course menu">☰</button>
        <span class="gd-title">${title}</span>
        <ol class="gd-dots" aria-label="Chapters">${chapters.map((chapter, i) => `<li><button type="button" data-chapter="${i}" aria-label="Chapter ${i + 1}: ${chapter.title}" title="${chapter.title}"></button></li>`).join("")}</ol>
        ${DSL.modeSwitch(lessonId)}
      </header>
      <section class="gd-stage nr-stage" tabindex="-1"></section>
      <div class="nr-dock">
        <div class="nr-voice" aria-hidden="true"><i></i><i></i><i></i><i></i></div>
        <p class="nr-cap" aria-live="polite"></p>
        <span class="nr-turn" hidden></span>
        <div class="nr-choices" hidden></div>
      </div>
      <footer class="nr-transport">
        <button type="button" class="nr-btn nr-prev" aria-label="Previous chapter">⏮</button>
        <button type="button" class="nr-btn nr-play" aria-label="Pause">❚❚</button>
        <button type="button" class="nr-btn nr-replay" aria-label="Replay chapter">↺</button>
        <span class="nr-chapter"></span>
        <button type="button" class="nr-btn nr-words" aria-label="Keywords" aria-expanded="false" hidden>📚 <b>0</b></button>
        <button type="button" class="nr-btn nr-speed" aria-label="Playback speed"></button>
        <button type="button" class="nr-btn nr-mute" aria-pressed="false"></button>
        <button type="button" class="nr-btn nr-next" aria-label="Next chapter">⏭</button>
      </footer>
      <div class="nr-words-panel" hidden>
        <div class="nr-words-card" role="dialog" aria-label="Keywords">
          <header><b>Keywords</b><small>Star the ones you want to practise</small><button type="button" class="nr-words-close" aria-label="Close keywords">✕</button></header>
          <div class="nr-words-body"></div>
          <footer><a href="#/flashcards">Open flashcards →</a></footer>
        </div>
      </div>
      <div class="nr-start">
        <div class="nr-start-card">
          <span class="nr-start-eyebrow">🎧 Narrated lesson</span>
          <h1>${title.replace(/^\d+\s·\s/, "")}</h1>
          <p>Sound on. The narrator walks you through, and stops whenever it's your turn.</p>
          <button type="button" class="button primary gd-big nr-go">▶ ${index > 0 ? `Resume · ${chapters[index].title}` : "Start"}</button>
          ${index > 0 ? `<button type="button" class="button ghost nr-over">Start over</button>` : ""}
        </div>
      </div>
    </div>`;

    const el = (selector) => root.querySelector(selector);
    const stage = el(".nr-stage");
    const dock = el(".nr-dock");
    const cap = el(".nr-cap");
    const turn = el(".nr-turn");
    const choices = el(".nr-choices");
    const playButton = el(".nr-play");
    const speedButton = el(".nr-speed");
    const muteButton = el(".nr-mute");
    const wordsButton = el(".nr-words");
    const wordsPanel = el(".nr-words-panel");
    // Words flown to the button in this playthrough; the count shows every word seen in the lesson.
    const collected = new Set();
    let resumeAfterWords = false;
    wordsButton.hidden = !Object.keys(lessonWords).length;
    if (DSL.Vocab) DSL.Vocab.wireCards(wordsPanel);
    const paintWordCount = () => {
      const seenCount = Object.keys(lessonWords).filter((id) => collected.has(id) || (DSL.Vocab && DSL.Vocab.hasSeen(id))).length;
      wordsButton.querySelector("b").textContent = String(seenCount);
    };
    paintWordCount();
    window.addEventListener("dsl-vocab", paintWordCount);

    // A keyword in a caption: light it up and send a copy to the Keywords button.
    function collect(id) {
      if (!lessonWords[id] || collected.has(id)) return;
      collected.add(id);
      const span = cap.querySelector(`.kw[data-kw="${id}"]`);
      const first = DSL.Vocab ? DSL.Vocab.seen(id, lessonId) : false;
      paintWordCount();
      if (span) span.classList.add("kw-new");
      const land = () => retrigger(wordsButton, "ping");
      if (span && !reducedMotion()) DSL.LabKit.fly(span, wordsButton, { duration: 750, lift: 60, className: "nr-kw-flyer" }).then(land);
      else land();
      if (first && span) DSL.LabKit.floater(span, "new keyword", "");
    }

    function openWords() {
      const ids = Object.keys(lessonWords).filter((id) => collected.has(id) || (DSL.Vocab && DSL.Vocab.hasSeen(id)));
      const hidden = Object.keys(lessonWords).length - ids.length;
      el(".nr-words-body").innerHTML = (ids.length && DSL.Vocab ? DSL.Vocab.listMarkup(ids) : `<p class="nr-words-empty">Keywords light up in the captions as they come up.</p>`)
        + (hidden ? `<p class="nr-words-more">${hidden} more to discover in this lesson.</p>` : "");
      resumeAfterWords = started && !clock.paused;
      clock.set(true);
      wordsPanel.hidden = false;
      wordsButton.setAttribute("aria-expanded", "true");
      el(".nr-words-close").focus({ preventScroll: true });
    }

    function closeWords() {
      if (wordsPanel.hidden) return;
      wordsPanel.hidden = true;
      wordsButton.setAttribute("aria-expanded", "false");
      if (resumeAfterWords) clock.set(false);
    }

    function persist() {
      writeJson(saveKey, { index, done: [...done] });
    }

    function paintChrome() {
      root.querySelectorAll(".gd-dots button").forEach((dot, i) => {
        dot.className = `${done.has(chapters[i].id) ? "done" : ""}${i === index ? " current" : ""}`;
      });
      el(".nr-chapter").textContent = `${index + 1} / ${chapters.length} · ${chapters[index].title}`;
      el(".nr-prev").disabled = index === 0;
      el(".nr-next").disabled = index === chapters.length - 1;
      speedButton.textContent = `${prefs.speed}×`;
      muteButton.textContent = prefs.muted ? "🔇" : "🔊";
      muteButton.setAttribute("aria-pressed", String(prefs.muted));
      muteButton.setAttribute("aria-label", prefs.muted ? "Unmute narrator" : "Mute narrator");
    }

    function paintPlay() {
      playButton.textContent = clock.paused ? "▶" : "❚❚";
      playButton.setAttribute("aria-label", clock.paused ? "Play" : "Pause");
      dock.classList.toggle("paused", clock.paused);
    }
    clock.listen(paintPlay);

    function caption(id, vars = {}) {
      const line = lines[id];
      const text = line ? (typeof line === "string" ? line : line.caption) : `[missing line: ${id}]`;
      const speaker = line && typeof line === "object" ? line.speaker : "";
      const label = speaker ? (speakers[speaker] && speakers[speaker].label) || speaker : "";
      cap.dataset.speaker = speaker || "";
      const found = [];
      const html = text
        .replace(/\{(\w+)\}/g, (match, key) => (key in vars ? vars[key] : match))
        .replace(/<k(?:\s+id="([^"]+)")?>([\s\S]*?)<\/k>/g, (match, keyId, inner) => {
          const key = keyId || slug(inner);
          found.push(key);
          return `<span class="kw" data-kw="${key}">${inner}</span>`;
        });
      cap.innerHTML = (label ? `<span class="nr-speaker">${label}</span>` : "") + html;
      retrigger(cap, "nr-cap-in");
      found.forEach(collect);
    }

    function setTurn(label) {
      turn.hidden = !label;
      turn.textContent = label || "";
      dock.classList.toggle("waiting", Boolean(label));
      if (label) retrigger(turn, "nr-turn-in");
    }

    function makeNarration(t, scene) {
      const alive = () => t === token && root.contains(scene);
      const after = (promise) => Promise.resolve(promise).then((value) => (alive() ? value : never()));

      let reacting = Promise.resolve();

      async function say(id, vars) {
        if (!alive()) return never();
        await after(reacting);
        await after(clock.ready());
        caption(id, vars);
        dock.classList.add("speaking");
        await after(voice.play(id));
        dock.classList.remove("speaking");
        await after(clock.sleep(LINE_GAP));
      }

      // A line spoken over the action without stopping it (a reaction mid-game). The next say waits for it.
      function react(id, vars) {
        if (!alive()) return never();
        caption(id, vars);
        dock.classList.add("speaking");
        reacting = voice.play(id).then(() => dock.classList.remove("speaking"));
        return after(reacting);
      }

      // Stop the film until the learner acts: setup(finish) wires listeners and calls finish(value),
      // or pass a promise (like the one mount returns) to wait for it.
      function ask(setup, { hint, highlight, label = "Your turn" } = {}) {
        if (!alive()) return never();
        if (typeof setup.then === "function") {
          const pending = setup;
          setup = (finish) => pending.then(finish);
        }
        setTurn(label);
        return after(new Promise((resolve) => {
          let settled = false;
          let hinting = false;
          const targets = () => (highlight ? [...scene.querySelectorAll(highlight)] : []);
          const finish = (value) => {
            if (settled || !alive()) return;
            settled = true;
            setTurn("");
            targets().forEach((target) => target.classList.remove("nr-nudge"));
            if (hinting) voice.stop();
            resolve(value);
          };
          clock.sleep(IDLE_HINT).then(() => {
            if (settled || !alive()) return;
            targets().forEach((target) => target.classList.add("nr-nudge"));
            if (hint) {
              hinting = true;
              react(hint).then(() => { hinting = false; });
            }
          });
          setup(finish);
        }));
      }

      // Put a Guided beat on stage now; the returned promise resolves when it calls done().
      // Its say() text shows as a silent caption; event(name, data) calls reach onEvent.
      function mount(beat, { onEvent } = {}) {
        return new Promise((finish) => beat.mount(scene, {
          state,
          alive,
          after,
          wait,
          prompt() {},
          say(html) {
            if (!alive() || !html) return;
            cap.innerHTML = html;
            retrigger(cap, "nr-cap-in");
          },
          done: () => finish(),
          lab,
          restart,
          event(name, data) {
            if (alive() && onEvent) onEvent(name, data);
          },
        }));
      }

      function wait(ms) {
        return after(clock.sleep(reducedMotion() ? Math.min(ms, 80) : ms));
      }

      function lab(labId) {
        if (onLab) onLab(labId);
      }

      // Stop the film for a response. options = [[key, label], …] → resolves with the chosen key.
      function choose(options, { label = "Your call" } = {}) {
        if (!alive()) return never();
        setTurn(label);
        choices.innerHTML = options.map(([key, text], i) => `<button type="button" class="nr-choice" data-key="${key}" style="--i:${i}"><kbd>${i + 1}</kbd>${text}</button>`).join("");
        choices.hidden = false;
        return after(new Promise((resolve) => {
          const pick = (button) => {
            if (!button || !alive()) return;
            choiceKeys = null;
            button.classList.add("picked");
            choices.querySelectorAll(".nr-choice").forEach((other) => { other.disabled = true; });
            clock.sleep(reducedMotion() ? 0 : 420).then(() => {
              choices.hidden = true;
              choices.innerHTML = "";
              setTurn("");
              resolve(button.dataset.key);
            });
          };
          choices.onclick = (event) => pick(event.target.closest(".nr-choice"));
          choiceKeys = (digit) => pick(choices.querySelectorAll(".nr-choice")[digit - 1]);
        }));
      }

      return {
        state,
        alive,
        after,
        say,
        react,
        ask,
        mount,
        choose,
        wait,
        show: (fn) => after(fn()),
        lab,
      };
    }

    async function play(i, direction = 1) {
      token += 1;
      const t = token;
      voice.stop();
      clock.set(false);
      choiceKeys = null;
      choices.hidden = true;
      choices.innerHTML = "";
      setTurn("");
      dock.classList.remove("speaking");
      cap.innerHTML = "";
      index = i;
      persist();
      paintChrome();

      const chapter = chapters[i];
      const old = stage.firstElementChild;
      const scene = document.createElement("div");
      scene.className = "gd-scene";
      stage.appendChild(scene);
      if (old) {
        if (!reducedMotion() && !(direction > 0 && chapter.continues)) {
          old.style.position = "absolute";
          old.style.inset = "0";
          old.animate([{ opacity: 1 }, { opacity: 0, transform: `translateX(${direction > 0 ? -48 : 48}px)` }], { duration: 220, easing: "ease-in" }).onfinish = () => old.remove();
          scene.animate([{ opacity: 0, transform: `translateX(${direction > 0 ? 48 : -48}px)` }, { opacity: 1, transform: "none" }], { duration: 320, easing: "cubic-bezier(.2,.8,.3,1)" });
        } else {
          old.remove();
        }
      }

      const n = makeNarration(t, scene);
      await chapter.script(n, scene);
      if (t !== token) return;
      done.add(chapter.id);
      persist();
      paintChrome();
      if (i < chapters.length - 1) {
        await n.wait(600);
        play(i + 1, 1);
      }
    }

    function restart() {
      done.clear();
      Object.keys(state).forEach((key) => delete state[key]);
      play(0, -1);
    }

    function start(from) {
      started = true;
      voice.unlock();
      const overlay = el(".nr-start");
      overlay.classList.add("gone");
      DSL.setTimer(() => overlay.remove(), 400);
      play(from, 1);
    }

    el(".nr-go").addEventListener("click", () => start(index));
    const over = el(".nr-over");
    if (over) over.addEventListener("click", () => {
      done.clear();
      Object.keys(state).forEach((key) => delete state[key]);
      start(0);
    });
    playButton.addEventListener("click", () => clock.set(!clock.paused));
    el(".nr-prev").addEventListener("click", () => play(index - 1, -1));
    el(".nr-next").addEventListener("click", () => play(index + 1, 1));
    el(".nr-replay").addEventListener("click", () => play(index, -1));
    speedButton.addEventListener("click", () => {
      prefs.speed = SPEEDS[(SPEEDS.indexOf(prefs.speed) + 1) % SPEEDS.length];
      writeJson(PREFS_KEY, prefs);
      voice.setSpeed();
      paintChrome();
    });
    muteButton.addEventListener("click", () => {
      prefs.muted = !prefs.muted;
      writeJson(PREFS_KEY, prefs);
      paintChrome();
    });
    cap.addEventListener("click", () => voice.stop());
    wordsButton.addEventListener("click", () => (wordsPanel.hidden ? openWords() : closeWords()));
    el(".nr-words-close").addEventListener("click", closeWords);
    wordsPanel.addEventListener("click", (event) => { if (event.target === wordsPanel) closeWords(); });
    root.querySelector(".gd-dots").addEventListener("click", (event) => {
      const dot = event.target.closest("[data-chapter]");
      if (!dot || !started) return;
      const target = Number(dot.dataset.chapter);
      play(target, target >= index ? 1 : -1);
    });

    const onVisibility = () => { if (document.hidden && started) clock.set(true); };
    document.addEventListener("visibilitychange", onVisibility);

    active = {
      root,
      key(event) {
        if (event.key === "Escape" && !wordsPanel.hidden) { closeWords(); return; }
        if (!started || event.target.closest("input, textarea, select")) return;
        if (/^[1-9]$/.test(event.key) && choiceKeys) {
          event.preventDefault();
          choiceKeys(Number(event.key));
        } else if ((event.key === " " || event.key === "k") && !event.target.closest("button")) {
          event.preventDefault();
          clock.set(!clock.paused);
        }
      },
    };

    DSL.onLeave(() => {
      token += 1;
      voice.stop();
      clock.set(false);
      document.removeEventListener("visibilitychange", onVisibility);
      window.removeEventListener("dsl-vocab", paintWordCount);
      active = null;
    });
    paintChrome();
    paintPlay();
  }

  document.addEventListener("keydown", (event) => {
    if (active && active.root.querySelector(".nr")) active.key(event);
  });

  DSL.Narrator = Object.freeze({ run, register, keywords });
})(window.DataSystemsLab);
